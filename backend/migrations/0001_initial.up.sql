CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  username TEXT NOT NULL UNIQUE,
  password TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS products (
  id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY, 
  sku TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  category TEXT NOT NULL,
  brand TEXT NOT NULL,
  slug TEXT NOT NULL UNIQUE,
  original_price BIGINT NOT NULL,
  discount SMALLINT NULL CHECK (discount BETWEEN 0 AND 100),
  stock INT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS product_images(
  id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY, 
  product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  image TEXT NOT NULL,
  is_primary BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE UNIQUE INDEX idx_one_primary_per_product
  ON product_images(product_id) WHERE is_primary = TRUE;

CREATE TABLE IF NOT EXISTS product_reviews(
  id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY, 
  product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  star_count SMALLINT NOT NULL CHECK (star_count BETWEEN 1 AND 5),
  description TEXT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS bundles(
  id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY, 
  name TEXT NOT NULL,
  label TEXT NOT NULL,
  total_price BIGINT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS bundle_details(
  id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY, 
  bundle_id BIGINT NOT NULL REFERENCES bundles(id) ON DELETE CASCADE,
  product_id BIGINT NOT NULL REFERENCES products(id),
  quantity INT NOT NULL DEFAULT 1 CHECK (quantity > 0), 
  UNIQUE (bundle_id, product_id)
);